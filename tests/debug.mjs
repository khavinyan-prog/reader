import { chromium, devices } from 'playwright';
import fs from 'fs';
const stub = fs.readFileSync('tests/speech-stub.js', 'utf8');
const browser = await chromium.launch({ channel: 'msedge' });
const ctx = await browser.newContext({ ...devices['iPhone 13'] });
await ctx.addInitScript(stub);
const page = await ctx.newPage();
page.on('console', (m) => console.log('console', m.type(), m.text()));
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.goto('http://localhost:8765/?nosw');
await page.setInputFiles('#file', process.argv[2]);
await page.waitForFunction(() => document.querySelectorAll('#text .s').length > 0);
await page.locator('#text .s').nth(6).click();
await new Promise(r => setTimeout(r, 3000));
console.log(await page.evaluate(() => JSON.stringify({ log: window.__ttsLog.slice(0, 12), cur: window.__reader.curId, playing: window.__reader.playing, speaking: speechSynthesis.speaking, q: speechSynthesis.queue.length })));
await browser.close();
